"""
Завдання 3. normalize_phone(phone_number)

Нормалізує телефонні номери для SMS-розсилки до стандартного формату:
тільки цифри та символ '+' на початку.

Вимоги:
- phone_number — рядок з номером у довільному форматі.
- Видаліть усі символи, крім цифр та '+' (пробіли, дужки, дефіси,
  \\t, \\n тощо). Рекомендовано модуль re.
- Якщо міжнародного коду немає — додайте '+38'.
  * номер починається з '380' -> додається лише '+'
  * номер починається з '38' (без '0' далі, напр. 38050...) -> додається '+'
  * номер вже з '+' -> залишається як є (після чистки)
  * номер без коду (напр. 050...) -> додається '+38'
- Повертає нормалізований номер (рядок).

Приклад:
  "067\\t123 4567"      -> "+380671234567"
  "(095) 234-5678\\n"   -> "+380952345678"
  "+380 44 123 4567"   -> "+380441234567"
  "380501234567"       -> "+380501234567"
  "    +38(050)123-32-34" -> "+380501233234"
  "     0503451234"    -> "+380503451234"
  "(050)8889900"       -> "+380508889900"
  "38050-111-22-22"    -> "+380501112222"
  "38050 111 22 11   " -> "+380501112211"
"""

import re


# ---------- implementation  ----------
def normalize_phone(phone_number: str) -> str:
    cleaned = phone_number.strip()
    has_plus = cleaned.startswith("+")
    digits = re.sub(r"\D", "", cleaned)

    if has_plus:
        return f"+{digits}"
    elif digits.startswith("38"):
        return f"+{digits}"
    else:
        return f"+38{digits}"


# ---------- tests  ----------
# приклади із завдання
raw_numbers = [
    "067\t123 4567",
    "(095) 234-5678\n",
    "+380 44 123 4567",
    "380501234567",
    "    +38(050)123-32-34",
    "     0503451234",
    "(050)8889900",
    "38050-111-22-22",
    "38050 111 22 11   ",
]
expected = [
    "+380671234567",
    "+380952345678",
    "+380441234567",
    "+380501234567",
    "+380501233234",
    "+380503451234",
    "+380508889900",
    "+380501112222",
    "+380501112211",
]
assert [normalize_phone(n) for n in raw_numbers] == expected

# вже нормалізований номер лишається незмінним (ідемпотентність)
assert normalize_phone("+380501234567") == "+380501234567"
assert normalize_phone(normalize_phone("(050)8889900")) == "+380508889900"

# різні роздільники
assert normalize_phone("050.123.45.67") == "+380501234567"
assert normalize_phone("050-123-45-67") == "+380501234567"
assert normalize_phone("+38 (050) 123 45 67") == "+380501234567"
assert normalize_phone("\t\n 050 123 45 67 \t\n") == "+380501234567"

# літери та інші символи видаляються
assert normalize_phone("tel: 050-123-45-67") == "+380501234567"
assert normalize_phone("050 123 45 67 (viber)") == "+380501234567"

# результат — рядок, '+' лише на початку і лише один
result = normalize_phone("38(050)123-45-67")
assert isinstance(result, str)
assert result.startswith("+") and result.count("+") == 1
assert result[1:].isdigit()

# '+' посеред номера не повинен лишатися
assert normalize_phone("050+123+45+67") == "+380501234567"

print("Task 3: all asserts passed")
